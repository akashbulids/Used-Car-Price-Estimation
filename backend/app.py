logger.info("CORS middleware added")


# =========================================================
# INPUT DATA
# =========================================================

class CarData(BaseModel):

    brand: str
    fuel_type: str
    transmission: str
    service_history: str
    insurance_valid: str
    color: str
    make_year: int
    mileage_kmpl: float
    engine_cc: int
    owner_count: int
    accidents_reported: int


# =========================================================
# EXPLANATION DATA
# =========================================================

class ExplanationData(CarData):

    predicted_price: float


# =========================================================
# HOME ROUTE
# =========================================================

@app.get("/")
def home():

    return {
        "message": "FastAPI is working"
    }


# =========================================================
# GEMINI EXPLANATION
# =========================================================

def generate_llm_explanation(
    data,
    predicted_price
):

    prompt = f"""
You are a professional AI automotive valuation assistant.

Analyze the following used vehicle information and explain the
machine-learning predicted price in clear, professional,
customer-friendly English.

VEHICLE INFORMATION
-------------------

Brand: {data.brand}
Fuel Type: {data.fuel_type}
Transmission: {data.transmission}
Service History: {data.service_history}
Insurance Valid: {data.insurance_valid}
Color: {data.color}
Manufacturing Year: {data.make_year}
Mileage: {data.mileage_kmpl} km/l
Engine: {data.engine_cc} cc
Previous Owners: {data.owner_count}
Accidents Reported: {data.accidents_reported}

MACHINE LEARNING PREDICTION
---------------------------

Predicted Price: ₹{predicted_price:,.2f}

IMPORTANT:
The predicted price above is generated by the machine-learning model.

You must NOT change, recalculate, convert, or generate another price.

RETURN THE RESPONSE IN EXACTLY THIS FORMAT:

PRICE ASSESSMENT

• [One short sentence explaining the predicted price.]
• [One short sentence explaining the main reasons affecting the valuation.]

KEY FACTORS

✓ Positive: [Important positive factor.]
✓ Positive: [Another positive factor if applicable.]
⚠ Negative: [Important negative factor.]
⚠ Negative: [Another negative factor if applicable.]

RECOMMENDATION

• [One practical recommendation for the buyer or seller.]

STRICT RULES:

1. Use professional and natural English.
2. Show the predicted price only in Indian Rupees (₹).
3. Do not create another price.
4. Do not change the machine-learning predicted price.
5. Do not invent market prices, statistics, or vehicle information.
6. Use only the vehicle information provided above.
7. Keep every point short and easy to understand.
8. Keep each section separate.
9. Do not write long paragraphs.
10. Always include PRICE ASSESSMENT, KEY FACTORS, and RECOMMENDATION.
11. Use ✓ only for positive factors.
12. Use ⚠ only for negative factors.
13. Maximum 100 words.
"""

    try:

        # =================================================
        # GET API KEY
        # =================================================

        gemini_api_key = os.getenv(
            "GEMINI_API_KEY"
        )

        if not gemini_api_key:

            logger.warning(
                "GEMINI_API_KEY not found"
            )

            return "LLM explanation is not available."


        # =================================================
        # CREATE GEMINI CLIENT
        # =================================================

        client = genai.Client(
            api_key=gemini_api_key
        )


        # =================================================
        # CALL GEMINI
        # =================================================

        logger.info("Calling Gemini...")

        response = client.models.generate_content(

            model="models/gemini-3.5-flash-lite",

            contents=prompt
        )


        # =================================================
        # GET RESPONSE
        # =================================================

        explanation = response.text.strip()

        logger.info(
            "LLM explanation generated successfully"
        )

        return explanation


    except Exception as e:

        logger.exception(
            f"Error generating LLM explanation: {e}"
        )

        return "LLM explanation is currently unavailable."


# =========================================================
# ML PREDICTION ROUTE
# =========================================================

@app.post("/predict")
def predict(data: CarData):

    try:

        logger.info(
            f"Prediction request received "
            f"for brand={data.brand}"
        )


        # =================================================
        # CREATE DATAFRAME
        # =================================================

        input_data = pd.DataFrame([
            {
                "brand": data.brand,
                "fuel_type": data.fuel_type,
                "transmission": data.transmission,
                "service_history": data.service_history,
                "insurance_valid": data.insurance_valid,
                "color": data.color,
                "make_year": data.make_year,
                "mileage_kmpl": data.mileage_kmpl,
                "engine_cc": data.engine_cc,
                "owner_count": data.owner_count,
                "accidents_reported": data.accidents_reported
            }
        ])

        logger.info(
            "Input data converted to DataFrame"
        )


        # =================================================
        # PREPROCESS
        # =================================================

        transformed_data = preprocessor.transform(
            input_data
        )

        logger.info(
            "Preprocessing completed"
        )


        # =================================================
        # ML PREDICTION
        # =================================================

        prediction = model.predict(
            transformed_data
        )

        predicted_price_usd = float(
            prediction[0]
        )

        logger.info(
            f"Original ML prediction: "
            f"${predicted_price_usd:,.2f}"
        )


        # =================================================
        # CONVERT USD TO INR
        # =================================================

        predicted_price_inr = (
            predicted_price_usd * USD_TO_INR
        )

        logger.info(
            f"Converted INR prediction: "
            f"₹{predicted_price_inr:,.2f}"
        )


        # =================================================
        # RETURN INR PRICE
        # =================================================

        return {

            "predicted_price": predicted_price_inr,

            "currency": "INR"

        }


    except Exception as e:

        logger.exception(
            f"Error during prediction: {e}"
        )

        raise HTTPException(
            status_code=500,
            detail=str(e)
        )


