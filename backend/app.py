# GEMINI EXPLANATION ROUTE
# =========================================================

@app.post("/explain")
def explain(data: ExplanationData):

    try:

        logger.info(
            f"Explanation request received "
            f"for brand={data.brand}"
        )


        # =================================================
        # CALL GEMINI
        # =================================================

        explanation = generate_llm_explanation(
            data,
            data.predicted_price
        )


        # =================================================
        # RETURN EXPLANATION
        # =================================================

        return {

            "explanation": explanation

        }


    except Exception as e:

        logger.exception(
            f"Error during explanation: {e}"
        )

        raise HTTPException(
            status_code=500,
            detail=str(e)
        )